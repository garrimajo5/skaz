export function records(){const entries=bundledCatalog().bundle.entries;return Object.fromEntries(Object.entries(definitions).map(([slug,facts])=>{const id='srd51:2014:spell:'+slug,e=entries.find(e=>e.id===id);if(!e||e.ruleset!=='5e-2014'||e.source.usage!=='cc-by-4.0')throw Error('Missing licensed source '+id);return[id,{source:e.source,level:e.spell.level,text:e.text,facts}];}));}
export function render(){return `// Generated by scripts/build-spell-facts.mjs from checked SRD 5.1 (CC BY 4.0).
// Source attribution, changes and license remain attached to each exact snapshot.
const SkazSpellFacts = (()=>{
 const records=${JSON.stringify(records())};
 const names={dex:'ЛОВ',con:'ТЕЛ',wis:'МДР'};
 function summary(entry,level){
  const record=records[entry?.id];if(!record||entry.ruleset!=='5e-2014'||entry.kind!=='spell'||entry.spell?.level!==record.level||entry.source?.version!==record.source.version||entry.source?.url!==record.source.url||entry.text!==record.text)return null;
  const f=record.facts,parts=[];
  if(f.save)parts.push('спас '+names[f.save]);if(f.attack)parts.push('дальн. атака');
  if(f.damage){const validLevel=Number.isInteger(level)&&level>=1&&level<=20;let count=f.damage[0];if(f.cantrip&&validLevel)count=level>=17?4:level>=11?3:level>=5?2:1;
   const dice=count+'к'+f.damage[1]+(f.bonus?'+'+f.bonus:'');parts.push((f.projectiles?f.projectiles+'×('+dice+')':dice)+' '+f.type+(f.cantrip&&validLevel?'':' (база)'));}
  if(f.healing)parts.push('лечение '+f.healing[0]+'к'+f.healing[1]+(f.modifier?'+мод.':'')+' (база)');
  if(f.half)parts.push('успех: ½');if(f.effect)parts.push(f.effect);
  return parts.join(' · ');
 }
 return {summary,count:Object.keys(records).length};
})();
if(typeof module!=='undefined')module.exports=SkazSpellFacts;
`;}
export function coverage(){const all=bundledCatalog().bundle.entries.filter(e=>e.kind==='spell').map(e=>e.id).sort(),covered=Object.keys(records()).sort();return {ruleset:'5e-2014',source:'SRD 5.1',usage:'cc-by-4.0',total:all.length,covered,uncovered:all.filter(id=>!covered.includes(id)),limitations:'Only exact saved source snapshots receive quick facts. Others retain range/concentration/ritual and their full source card. Effects and upcasting are not applied automatically.'};}
if(process.argv[1]===fileURLToPath(import.meta.url)){await writeFile(new URL('../client/spell-facts.js',import.meta.url),render());await writeFile(new URL('../catalog/spell-quick-facts.coverage.json',import.meta.url),JSON.stringify(coverage(),null,2)+'\n');}
