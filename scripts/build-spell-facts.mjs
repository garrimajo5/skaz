export function records(){const entries=bundledCatalog().bundle.entries;return Object.fromEntries(Object.entries(definitions).map(([slug,facts])=>{const id='srd51:2014:spell:'+slug,e=entries.find(e=>e.id===id);if(!e||e.ruleset!=='5e-2014'||e.source.usage!=='cc-by-4.0')throw Error('Missing licensed source '+id);return[id,{source:e.source,level:e.spell.level,text:e.text,facts}];}));}
export function render(){return `// Generated by scripts/build-spell-facts.mjs from checked SRD 5.1 (CC BY 4.0).
// Source attribution, changes and license remain attached to each exact snapshot.
const SkazSpellFacts = (()=>{
 const records=${JSON.stringify(records())};
 // Edit this generator, then run node scripts/build-spell-facts.mjs.
 // Rule calculation contains codes/numbers only; Russian belongs to format().
 function cantripDiceCount(level){return level>=17?4:level>=11?3:level>=5?2:1;}
 /** Pure calculation for exact checked snapshots; unknown level retains base dice.
  * Dice are {count, sides}; types/abilities/effects are stable codes, not labels.
  * Damage basis is character-level or base; healing remains a base spell effect.
  */
 function calculate(entry,level){
  const record=Object.hasOwn(records,entry?.id)?records[entry.id]:null;
  if(!record||entry.ruleset!=='5e-2014'||entry.kind!=='spell'||entry.spell?.level!==record.level||entry.source?.version!==record.source.version||entry.source?.url!==record.source.url||entry.text!==record.text)return null;
  const f=record.facts,knownLevel=Number.isInteger(level)&&level>=1&&level<=20;
  const scaled=f.cantrip&&knownLevel;
  return {
   savingThrow:f.save??null,
   attack:f.attack??null,
   damage:f.damage?{dice:{count:scaled?cantripDiceCount(level):f.damage[0],sides:f.damage[1]},bonus:f.bonus??0,type:f.type,projectiles:f.projectiles??null,basis:scaled?'character-level':'base'}:null,
   healing:f.healing?{dice:{count:f.healing[0],sides:f.healing[1]},addSpellcastingModifier:!!f.modifier,basis:'base'}:null,
   onSuccessfulSave:f.half?{damageMultiplier:0.5}:null,
   effect:f.effect??null,
  };
 }
 /** Common plain-text presentation for catalog and play; never HTML. */
 function format(facts){
  if(!facts)return null;
  const ru={
   save:'спас ',abilities:{dex:'ЛОВ',con:'ТЕЛ',wis:'МДР'},attack:'дальн. атака',
   types:{acid:'кислота',necrotic:'некротический',fire:'огонь',cold:'холод',poison:'яд',radiant:'излучение',psychic:'психический',force:'силовое поле',thunder:'звук',lightning:'электричество'},
   healing:'лечение ',modifier:'+мод.',base:' (база)',half:'успех: ½',
   effects:{'humanoid-paralysis':'паралич гуманоида'},die:'к',separator:' · ',
  };
  const dice=value=>value.count+ru.die+value.sides,parts=[];
  if(facts.savingThrow)parts.push(ru.save+ru.abilities[facts.savingThrow]);
  if(facts.attack)parts.push(ru.attack);
  if(facts.damage){const d=facts.damage,roll=dice(d.dice)+(d.bonus?'+'+d.bonus:'');
   parts.push((d.projectiles?d.projectiles+'×('+roll+')':roll)+' '+ru.types[d.type]+(d.basis==='base'?ru.base:''));}
  if(facts.healing){const h=facts.healing;parts.push(ru.healing+dice(h.dice)+(h.addSpellcastingModifier?ru.modifier:'')+ru.base);}
  if(facts.onSuccessfulSave?.damageMultiplier===0.5)parts.push(ru.half);
  if(facts.effect)parts.push(ru.effects[facts.effect]);
  return parts.join(ru.separator);
 }
 function summary(entry,level){return format(calculate(entry,level));}
 return {calculate,format,summary,count:Object.keys(records).length};
})();
if(typeof module!=='undefined')module.exports=SkazSpellFacts;
`;}
export function coverage(){const all=bundledCatalog().bundle.entries.filter(e=>e.kind==='spell').map(e=>e.id).sort(),covered=Object.keys(records()).sort();return {ruleset:'5e-2014',source:'SRD 5.1',usage:'cc-by-4.0',total:all.length,covered,uncovered:all.filter(id=>!covered.includes(id)),limitations:'Only exact saved source snapshots receive quick facts. Others retain range/concentration/ritual and their full source card. Effects and upcasting are not applied automatically.'};}
if(process.argv[1]===fileURLToPath(import.meta.url)){await writeFile(new URL('../client/spell-facts.js',import.meta.url),render());await writeFile(new URL('../catalog/spell-quick-facts.coverage.json',import.meta.url),JSON.stringify(coverage(),null,2)+'\n');}
